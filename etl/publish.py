"""
publish.py — copy the Gold star schema into Postgres schema `dw` (Supabase).

    python -m etl.publish --sql out/dw_publish.sql     # write a SQL file (paste in SQL Editor)
    python -m etl.publish                               # publish to $LOWROX_DW_DSN

Every run replaces the `dw` tables in one transaction, so readers never see a
half-published warehouse. The schema is not exposed to the web app: anon and
authenticated get no USAGE on it, and the Supabase API does not serve it unless
someone adds it under API → Exposed schemas.
"""
from __future__ import annotations

import argparse
import math
import os
import sys
from datetime import date, datetime
from pathlib import Path

import pandas as pd
from deltalake import DeltaTable

from .config import GOLD

SCHEMA = "dw"

# The design (Data warehouse schema slide): 9 dimensions, 5 facts.
TABLES: dict[str, list[str]] = {     # table -> primary key
    "dim_day": ["day_key"],
    "dim_user": ["user_key"],
    "dim_user_profile": ["user_profile_key"],
    "dim_area": ["area_key"],
    "dim_workout_type": ["workout_type_key"],
    "dim_device": ["device_key"],
    "dim_workout_info": ["workout_info_key"],
    "dim_plan": ["plan_key"],
    "dim_event": ["event_key"],
    "fct_workout_session": ["workout_id"],
    "fct_event_participation": ["participation_id"],
    "fct_subscription_payment": ["payment_id"],
    "fct_notification_delivery": ["notification_id"],
    "fct_user_fitness_weekly": ["user_key", "week_start"],
}

COMMENTS = {
    "dim_user": "SCD type 2; email only as a one-way email_token",
    "dim_user_profile": "mini-dimension: age band x gender x fitness level, as of each fact",
    "dim_device": "key 0 = manual entry",
    "dim_workout_info": "junk dimension: entry method, heart-rate / calories present, event session",
    "fct_workout_session": "transaction: one row per validated workout",
    "fct_event_participation": "transaction: one row per user joining an event",
    "fct_subscription_payment": "transaction: one row per payment attempt",
    "fct_notification_delivery": "accumulating snapshot: one row per notification",
    "fct_user_fitness_weekly": "periodic snapshot: one row per user per week, zero weeks included",
}


def _pg_type(s: pd.Series) -> str:
    if pd.api.types.is_bool_dtype(s):
        return "boolean"
    if pd.api.types.is_integer_dtype(s):
        return "bigint"
    if pd.api.types.is_float_dtype(s):
        return "double precision"
    if pd.api.types.is_datetime64_any_dtype(s):
        return "timestamptz"
    return "text"


def _literal(v) -> str:
    if v is None or v is pd.NaT or (isinstance(v, float) and math.isnan(v)):
        return "NULL"
    try:
        if pd.isna(v):
            return "NULL"
    except (TypeError, ValueError):
        pass
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int,)) or (hasattr(v, "dtype") and pd.api.types.is_integer_dtype(type(v))):
        return str(int(v))
    if isinstance(v, float):
        return repr(float(v))
    if isinstance(v, (pd.Timestamp, datetime)):
        return "'" + pd.Timestamp(v).isoformat() + "'"
    if isinstance(v, date):
        return "'" + v.isoformat() + "'"
    try:                                   # numpy scalars
        import numpy as np
        if isinstance(v, np.integer):
            return str(int(v))
        if isinstance(v, np.floating):
            return "NULL" if np.isnan(v) else repr(float(v))
        if isinstance(v, np.bool_):
            return "true" if v else "false"
    except ImportError:
        pass
    return "'" + str(v).replace("'", "''") + "'"


def read_gold_tables() -> dict[str, pd.DataFrame]:
    out = {}
    for t in TABLES:
        p = GOLD / t
        if not (p / "_delta_log").exists():
            raise SystemExit(f"gold.{t} not found under {GOLD} — run the pipeline first")
        out[t] = DeltaTable(str(p)).to_pandas()
    return out


def build_sql(tables: dict[str, pd.DataFrame], *, batch: int = 500) -> str:
    lines = [
        "-- Lowrox data warehouse (Gold) -> Supabase schema dw. Generated by etl/publish.py.",
        "-- Replaces every dw table in one transaction. Not exposed to the web app.",
        "BEGIN;",
        # sql/13 creates dw for lowrox_dw_writer, which may not create schemas itself
        "DO $$ BEGIN",
        f"  IF NOT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = '{SCHEMA}') THEN",
        f"    EXECUTE 'CREATE SCHEMA {SCHEMA}';",
        "  END IF;",
        "END $$;",
        f"REVOKE ALL ON SCHEMA {SCHEMA} FROM PUBLIC;",
        "DO $$ BEGIN",
        "  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN",
        f"    EXECUTE 'REVOKE ALL ON SCHEMA {SCHEMA} FROM anon, authenticated';",
        "  END IF;",
        "END $$;",
    ]
    for name, df in tables.items():
        cols = list(df.columns)
        defs = [f'  "{c}" {_pg_type(df[c])}' for c in cols]
        pk = TABLES[name]
        lines.append(f"DROP TABLE IF EXISTS {SCHEMA}.{name};")
        lines.append(f"CREATE TABLE {SCHEMA}.{name} (\n" + ",\n".join(defs)
                     + f",\n  PRIMARY KEY ({', '.join(pk)})\n);")
        if name in COMMENTS:
            lines.append(f"COMMENT ON TABLE {SCHEMA}.{name} IS '{COMMENTS[name]}';")
        col_list = ", ".join(f'"{c}"' for c in cols)
        records = df.to_dict("records")
        for i in range(0, len(records), batch):
            chunk = records[i:i + batch]
            values = ",\n".join("(" + ", ".join(_literal(r[c]) for c in cols) + ")" for r in chunk)
            lines.append(f"INSERT INTO {SCHEMA}.{name} ({col_list}) VALUES\n{values};")
    lines.append(f"REVOKE ALL ON ALL TABLES IN SCHEMA {SCHEMA} FROM PUBLIC;")
    lines.append("DO $$ BEGIN")
    lines.append("  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN")
    lines.append(f"    EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA {SCHEMA} FROM anon, authenticated';")
    lines.append("  END IF;")
    lines.append("END $$;")
    lines.append("COMMIT;")
    lines.append("")
    lines.append("-- Check: SELECT table_name, (xpath('/row/c/text()', query_to_xml(format('SELECT count(*) AS c FROM dw.%I', table_name), false, true, '')))[1]::text::int AS rows")
    lines.append("--        FROM information_schema.tables WHERE table_schema = 'dw' ORDER BY 1;")
    return "\n".join(lines) + "\n"


def publish(dsn: str, sql: str) -> None:
    import psycopg2
    conn = psycopg2.connect(dsn)
    try:
        with conn, conn.cursor() as cur:
            # the script carries its own BEGIN/COMMIT
            cur.execute(sql.replace("BEGIN;", "", 1).replace("COMMIT;", "", 1))
    finally:
        conn.close()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--sql", help="write the SQL to this file instead of publishing")
    args = ap.parse_args(argv)
    tables = read_gold_tables()
    sql = build_sql(tables)
    rows = {k: len(v) for k, v in tables.items()}
    if args.sql:
        Path(args.sql).parent.mkdir(parents=True, exist_ok=True)
        Path(args.sql).write_text(sql, encoding="utf-8")
        print(f"wrote {args.sql}: {sum(rows.values())} rows in {len(rows)} tables")
        return 0
    dsn = os.environ.get("LOWROX_DW_DSN")
    if not dsn:
        print("LOWROX_DW_DSN is not set (use --sql to write a file instead)", file=sys.stderr)
        return 2
    publish(dsn, sql)
    print(f"published dw: {rows}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
